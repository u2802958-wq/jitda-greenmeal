/* ==========================================================================
   🦉 올빼미 급식 비교소 — 1단계 app.js
   --------------------------------------------------------------------------
   이번 단계 목표
     · index.html 과 app.js 가 서로 연결되었는지 확인한다
     · 날짜 칸에 오늘 날짜를 자동으로 넣는다
     · 시도교육청 목록을 자바스크립트로 만들어 넣는다
     · 버튼을 누르면 반응하게 한다

   ⚠️ 아직 급식은 안 나옵니다. 그건 3단계에서 합니다!
   ========================================================================== */
'use strict';

/* --------------------------------------------------------------------------
   ① 자주 쓰는 짧은 도구
   document.querySelector('#date') 는 너무 길어서 $('#date') 로 줄여 씁니다.
   -------------------------------------------------------------------------- */
const $  = (sel, root = document) => root.querySelector(sel);
const $$ = (sel, root = document) => Array.from(root.querySelectorAll(sel));

/* --------------------------------------------------------------------------
   ② 17개 시도교육청 코드
   NEIS가 정해 둔 코드입니다. L10, O10 은 없습니다. (그대로 적어야 합니다)
   -------------------------------------------------------------------------- */
const SIDO_LIST = [
  ['', '전국(시도 상관없이)'],
  ['B10', '서울특별시교육청'], ['C10', '부산광역시교육청'],
  ['D10', '대구광역시교육청'], ['E10', '인천광역시교육청'],
  ['F10', '광주광역시교육청'], ['G10', '대전광역시교육청'],
  ['H10', '울산광역시교육청'], ['I10', '세종특별자치시교육청'],
  ['J10', '경기도교육청'],     ['K10', '강원특별자치도교육청'],
  ['M10', '충청북도교육청'],   ['N10', '충청남도교육청'],
  ['P10', '전북특별자치도교육청'], ['Q10', '전라남도교육청'],
  ['R10', '경상북도교육청'],   ['S10', '경상남도교육청'],
  ['T10', '제주특별자치도교육청'],
];

/* --------------------------------------------------------------------------
   ③ 오늘 날짜를 2026-08-07 모양으로 만들기
   padStart(2,'0') 은 8 을 08 로 바꿔 줍니다.
   -------------------------------------------------------------------------- */
function todayISO() {
  const d = new Date();
  const p = n => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`;
}

/* --------------------------------------------------------------------------
   ④ 알림줄에 글씨 보여 주기
   -------------------------------------------------------------------------- */
function setStatus(html, kind = '') {
  const box = $('#status');
  if (!html) { box.hidden = true; box.innerHTML = ''; return; }
  box.hidden = false;
  box.className = 'status ' + kind;
  box.innerHTML = html;
}

/* --------------------------------------------------------------------------
   ⑤ 앱 시작하기
   -------------------------------------------------------------------------- */
function init() {
  // (1) 날짜 칸에 오늘 날짜 넣기
  $('#date').value = todayISO();

  // (2) 시도교육청 <select> 두 개를 똑같이 채우기
  //     '전국(시도 상관없이)' → <option value="">전국(시도 상관없이)</option>
  $$('.sido').forEach(sel => {
    sel.innerHTML = SIDO_LIST
      .map(([code, name]) => `<option value="${code}">${name.replace('교육청', '')}</option>`)
      .join('');
  });

  // (3) 비교하기 버튼이 눌리는지 확인 (아직 진짜 비교는 못 합니다)
  $('#compareBtn').addEventListener('click', () => {
    const 날짜 = $('#date').value;
    const 끼니 = $('#mealType').options[$('#mealType').selectedIndex].text;
    setStatus(`버튼이 눌렸습니다! 고른 날짜는 <b>${날짜}</b>, 끼니는 <b>${끼니}</b>입니다.
               다음 단계에서 진짜 급식을 불러옵니다. 🎉`);
  });

  // (4) 검색 버튼도 눌리는지 확인
  $$('.searchBtn').forEach(btn => {
    btn.addEventListener('click', () => {
      setStatus('검색 기능은 <b>2단계</b>에서 만듭니다!', 'warn');
    });
  });

  setStatus('1단계 완성! 날짜가 오늘로 채워졌고 시도 목록이 만들어졌다면 성공입니다.');
}

// 이 한 줄이 있어야 위에 만든 init() 이 실제로 실행됩니다.
init();
